def create_incident(db: Session, payload: IncidentCreate) -> tuple[Incident, str]:
    check_values(payload.model_dump(mode="json"))
    incident = Incident(
        incident_type=payload.incident_type,
        payment_method=payload.payment_method,
        amount=payload.amount,
        incident_time=payload.incident_time,
        occurred_at=payload.incident_time,
        other_crime_sub_category=payload.other_crime_sub_category,
        details=payload.details,
        incident_subtype=payload.incident_subtype,
        affected_person_type=payload.affected_person_type,
        platform=payload.platform,
        account_type=payload.account_type,
        immediate_danger=payload.immediate_danger,
        threat_or_blackmail=payload.threat_or_blackmail,
        content_still_online=payload.content_still_online,
        account_access=payload.account_access,
        attacker_active=payload.attacker_active,
        sensitive_information_exposed=payload.sensitive_information_exposed,
        evidence_types=payload.evidence_types,
        urgency=Urgency.medium,
        status=IncidentStatus.draft,
    )
    from app.services.case_access import issue
    token = issue(incident)
    db.add(incident)
    db.flush()
    if payload.conversation_first or incident.incident_type == IncidentType.financial_fraud:
        facts = FACTS_ADAPTER.validate_python({"kind": "incident_understanding" if payload.conversation_first else "financial_authorization_unknown", "amount": payload.amount,
            "occurred_at": payload.incident_time, "payment_method": payload.payment_method})
        response_service.record_plan(db, incident, facts, as_of=datetime.now(timezone.utc))
        incident.status = IncidentStatus.draft
    else:
        incident.playbook_id = "legacy_nonfinancial"
    db.commit()
    db.refresh(incident)
    return incident, token


