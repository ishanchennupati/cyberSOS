# Deprecated compatibility data, generated by the canonical engine rather than
# maintaining a second financial decision table. No current route uses this table.
def build_action_list(urgency: Urgency, payment_method: PaymentMethod, *, large_amount: bool = False) -> list[ActionItem]:
    facts = FACTS_ADAPTER.validate_python({"kind": "financial_authorization_unknown", "payment_method": payment_method})
    plan = evaluate(facts, as_of=datetime(2026, 10, 1, tzinfo=timezone.utc))
    return [a.model_copy(update={"priority": urgency}) for a in plan.actions]

ACTION_PLAN_RULES = {(u, p): tuple(build_action_list(u, p)) for u in Urgency for p in PaymentMethod}
_RULE_ACTIONS = {a.id: a for a in build_action_list(Urgency.high, PaymentMethod.unknown)}

# --- Pure functions (unit-tested) --------------------------------------------


def is_large_amount(amount: float | Decimal | None) -> bool:
    value = _as_float(amount)
    if value is None:
        return False
    return value >= LARGE_AMOUNT_THRESHOLD


def compute_urgency(
    occurred_at: datetime,
    amount: float | Decimal | None,
    *,
    now: datetime | None = None,
) -> Urgency:
    """Deprecated compatibility helper; delegates to the versioned financial engine."""
    facts = FACTS_ADAPTER.validate_python({"kind": "financial_authorization_unknown", "occurred_at": occurred_at, "amount": amount})
    return evaluate(facts, as_of=now or datetime.now(timezone.utc)).urgency


def build_action_plan(incident: Incident, *, db: Session) -> ActionPlanResponse:
    if incident.incident_type in {IncidentType.women_children, IncidentType.other_cyber_crime}:
        return build_category_action_plan(incident)
    recorded = response_service.latest(db, incident.id)
    if recorded is None:
        raise ValueError("No versioned financial plan recorded")
    plan = ResponsePlan.model_validate(recorded.plan)
    if plan.facts.kind == 'incident_understanding':
        body = 'WORKING INCIDENT NOTES — review before using on an external official service.\n'
        body += 'Financial loss: ' + ('No known loss reported' if plan.facts.money_lost is False else 'Unknown') + '\n'
        body += 'Possible signals: ' + (', '.join(plan.facts.signals) or 'Still gathering information') + '\n'
        body += 'These interpreted details require your review. Preparing notes does not submit a complaint.'
        return ActionPlanResponse(urgency=plan.urgency, urgency_label='Still gathering information',
            core_message='Review your working understanding and applicable steps. Classification remains provisional.',
            large_amount=False, actions=list(plan.actions), complaint_draft=ComplaintDraft(body=body),
            playbook_id=plan.playbook_id, playbook_version=plan.playbook_version,
            fact_schema_version=plan.fact_schema_version, plan_revision=recorded.revision, urgency_reasons=[])
    body = render_complaint_draft(incident_type=incident.incident_type,
        occurred_at=plan.facts.occurred_at, amount=plan.facts.amount,
        payment_method=plan.facts.payment_method, transaction_id=plan.facts.transaction_id,
        urgency=plan.urgency, actions=list(plan.actions))
    body += "\nPayment authorization stated: " + {"authorized": "approved after deception", "unauthorized": "not authorized", "unknown": "unknown"}[plan.facts.authorization]
    return ActionPlanResponse(urgency=plan.urgency, urgency_label=URGENCY_BADGE[plan.urgency],
        core_message=CORE_MESSAGES[plan.urgency], large_amount=is_large_amount(plan.facts.amount),
        actions=list(plan.actions), complaint_draft=ComplaintDraft(body=body),
        playbook_id=plan.playbook_id, playbook_version=plan.playbook_version,
        fact_schema_version=plan.fact_schema_version, plan_revision=recorded.revision,
        urgency_reasons=[{"factor": "playbook", "rule_id": plan.playbook_id + "-" + plan.playbook_version,
            "human_readable_reason": r, "severity_contribution": plan.urgency.value} for r in plan.reasons])


